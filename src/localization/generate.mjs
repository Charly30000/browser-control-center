import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync, existsSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const defaultRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const localePattern = /^[a-zA-Z]{2,8}(?:-[a-zA-Z0-9]{2,8})*$/;
const manifestPattern = /^package\.nls(?:\.[a-zA-Z0-9-]+)?\.json$/;
const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));
const isRecord = (value) => typeof value === "object" && value !== null && !Array.isArray(value);
const placeholders = (value) => [...new Set([...value.matchAll(/\{(\w+)\}/g)].map((match) => match[1]))].sort();

/** Generates build artifacts only. Authored translations stay in locales/<language>.json. */
export const generateLocalization = (projectRoot = defaultRoot, { check = false } = {}) => {
  const directory = resolve(projectRoot, "src/localization");
  const localeDirectory = resolve(directory, "locales");
  const config = readJson(resolve(directory, "config.json"));
  if (!isRecord(config) || !isRecord(config.locales) || Object.keys(config.locales).length === 0) throw new Error("Register at least one locale in localization/config.json.");
  const registered = Object.keys(config.locales);
  if (!registered.includes(config.defaultLocale) || !registered.includes(config.fallbackLocale)) throw new Error("The default and fallback locales must be registered.");
  if (new Set(registered.map((locale) => locale.toLowerCase())).size !== registered.length) throw new Error("Locale codes must be unique regardless of case.");

  const catalogs = new Map();
  const files = new Map();
  for (const [locale, file] of Object.entries(config.locales)) {
    if (!localePattern.test(locale) || typeof file !== "string") throw new Error(`Invalid locale registration: ${locale}.`);
    const source = resolve(directory, file);
    const localPath = relative(localeDirectory, source);
    if (isAbsolute(localPath) || localPath.startsWith("..") || !source.endsWith(".json")) throw new Error(`Locale ${locale} must use a JSON file inside localization/locales.`);
    if ([...files.values()].includes(source)) throw new Error("Each locale must have its own catalog file.");
    const catalog = readJson(source);
    if (!isRecord(catalog) || !Object.values(catalog).every((value) => typeof value === "string" && value.trim() !== "")) throw new Error(`Locale ${locale} must contain nonempty string messages.`);
    catalogs.set(locale, catalog);
    files.set(locale, source);
  }
  const fallback = catalogs.get(config.fallbackLocale);
  for (const [locale, catalog] of catalogs) {
    for (const [key, value] of Object.entries(catalog)) {
      if (!Object.hasOwn(fallback, key)) throw new Error(`Unknown translation key ${key} in ${locale}.`);
      if (JSON.stringify(placeholders(value)) !== JSON.stringify(placeholders(fallback[key]))) throw new Error(`Placeholder mismatch for ${locale}:${key}.`);
    }
  }

  const manifestKeys = new Set();
  const collectKeys = (value) => {
    if (typeof value === "string") for (const match of value.matchAll(/%([^%]+)%/g)) manifestKeys.add(match[1]);
    else if (Array.isArray(value)) value.forEach(collectKeys);
    else if (isRecord(value)) Object.values(value).forEach(collectKeys);
  };
  collectKeys(readJson(resolve(projectRoot, "package.json")));
  for (const key of manifestKeys) if (!Object.hasOwn(fallback, key)) throw new Error(`Manifest translation ${key} is missing from the fallback catalog.`);

  const generatedDirectory = resolve(directory, "generated");
  const registry = [
    "// Generated by src/localization/generate.mjs. Edit config.json and locales/*.json instead.",
    ...registered.map((locale, index) => `import locale${index} from ${JSON.stringify(relative(generatedDirectory, files.get(locale)).replaceAll("\\", "/"))};`),
    "", "export const catalogs = {",
    ...registered.map((locale, index) => `  ${JSON.stringify(locale)}: locale${index}${index < registered.length - 1 ? "," : ""}`),
    "} as const;", `export const fallbackCatalog = catalogs[${JSON.stringify(config.fallbackLocale)}];`, ""
  ].join("\n");
  const outputs = new Map([[resolve(generatedDirectory, "catalogs.ts"), registry]]);
  const defaultCatalog = { ...fallback, ...catalogs.get(config.defaultLocale) };
  const manifest = (catalog) => Object.fromEntries([...manifestKeys].filter((key) => Object.hasOwn(catalog, key)).map((key) => [key, catalog[key]]));
  const manifestFiles = ["package.nls.json"];
  outputs.set(resolve(projectRoot, "package.nls.json"), JSON.stringify(manifest(defaultCatalog), null, 2) + "\n");
  for (const locale of registered.filter((locale) => locale !== config.defaultLocale)) {
    const file = `package.nls.${locale.toLowerCase()}.json`;
    manifestFiles.push(file);
    outputs.set(resolve(projectRoot, file), JSON.stringify(manifest(catalogs.get(locale)), null, 2) + "\n");
  }
  const inventoryFile = resolve(generatedDirectory, "manifest-files.json");
  const previous = existsSync(inventoryFile) ? readJson(inventoryFile) : [];
  if (!Array.isArray(previous) || !previous.every((file) => typeof file === "string" && manifestPattern.test(file))) throw new Error("Invalid generated manifest inventory.");
  outputs.set(inventoryFile, JSON.stringify(manifestFiles, null, 2) + "\n");
  for (const [file, content] of outputs) {
    if (existsSync(file) && readFileSync(file, "utf8").replaceAll("\r\n", "\n") === content) continue;
    if (check) throw new Error(`Localization output is stale: ${relative(projectRoot, file)}.`);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content, "utf8");
  }
  for (const file of previous.filter((file) => !manifestFiles.includes(file))) {
    const target = resolve(projectRoot, file);
    if (!existsSync(target)) continue;
    if (check) throw new Error(`Remove stale generated locale: ${file}.`);
    unlinkSync(target);
  }
  // Unregistered catalogs are allowed while a translation is being prepared.
  return { locales: registered, catalogFiles: readdirSync(localeDirectory).filter((file) => file.endsWith(".json")) };
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateLocalization(defaultRoot, { check: process.argv.includes("--check") });
}
